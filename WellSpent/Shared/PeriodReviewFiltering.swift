import WellSpentAPI

/// Pure derivation of the "carried over" list `PeriodReviewGateView` shows —
/// split out so it's unit-testable without a network call. See
/// docs/features/month-cycling-review.md.
///
/// The previous period's still-unpaid Fixed rows are deliberately *not*
/// derived here: that period isn't archived, so the real `TransactionsListView`
/// (embedded via `PeriodReviewTransactionsView`) already shows them correctly
/// — with the same swipe actions, mark/unmark paid, exclude toggle, and
/// Plaid category-only lock every other non-archived period gets. Reimplementing
/// any of that here would risk it drifting from the real rules.
nonisolated enum PeriodReviewFiltering {
    /// Rows in the newly-cycled period that were generated by carrying the
    /// previous period's ending balance forward.
    static func carriedOverTransactions(_ transactions: [Wellspent_V1_Transaction], previousPeriodID: String) -> [Wellspent_V1_Transaction] {
        transactions.filter { $0.carriedFromBudgetPeriodID == previousPeriodID }
    }
}
